// Inline the scene sources and emoji images into src/generated.ts so the Producer stays pure.
import { readFileSync, writeFileSync } from "node:fs";
const here = new URL("../", import.meta.url);
const read = path => readFileSync(new URL(path, here), "utf8");
const html = read("scene/scene.html").replace(/%%EMO_([0-9a-f]+)%%/g, (_, code) =>
  `data:image/webp;base64,${readFileSync(new URL(`assets/${code}.webp`, here)).toString("base64")}`);
const out = `// Generated by scripts/bundle.mjs from scene/ and assets/. Do not edit.
export const sceneHtml = ${JSON.stringify(html)};
export const sceneCss = ${JSON.stringify(read("scene/scene.css"))};
export const sceneSetup = ${JSON.stringify(read("scene/scene.js"))};
`;
writeFileSync(new URL("src/generated.ts", here), out);
